"""The lines NPCs say out loud in the open world, for the addon's NPC Chat part.

Writes addons/Spoken_Quests/ChatterLines.lua, which Chatter.lua matches arriving /say, /yell and
whisper chat against. The lines are the Forever world DB's creature_text rows (the TrinityCore
schema the repack and export_compendium.py read), by speaker: ChatterLines[creature id] = { { id,
text }, ... }.

Which rows are kept:
  - say, yell, whisper and boss whisper (creature_text.Type 12, 14, 15, 42). Emotes have no voice.
  - Sound = 0. A line the game plays its own recording for is already voiced.
  - BroadcastTextId <> 0. It is the line's id, as in FollowupLines.lua, and names its recording
    ({broadcastTextId}-{voice}) in the packs' FollowupLookup.
  - A speaker with a spawn on the open-world maps (0 and 1). In an instance the client hides the
    speaker's GUID, so such a line could never be matched.
A line is kept once per speaker, whichever group it is in.

Connection: COMPENDIUM_MYSQL_HOST, _PORT, _USER, _PASSWORD and _DATABASE, as export_compendium.py.
"""
import argparse
import os

DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "..", "..", "addons", "Spoken_Quests", "ChatterLines.lua")

OPEN_WORLD_MAPS = (0, 1)
CHAT_TYPES = (12, 14, 15, 42)

QUERY = f"""
SELECT ct.CreatureID, ct.BroadcastTextId, ct.Text
FROM creature_text ct
WHERE ct.Type IN ({", ".join(map(str, CHAT_TYPES))})
  AND ct.Sound = 0
  AND ct.BroadcastTextId <> 0
  AND ct.Text <> ''
  AND EXISTS (SELECT 1 FROM creature c WHERE c.id = ct.CreatureID AND c.map IN ({", ".join(map(str, OPEN_WORLD_MAPS))}))
ORDER BY ct.CreatureID, ct.GroupID, ct.ID
"""

NAMES = "SELECT entry, name FROM creature_template WHERE entry IN ({})"


def lua_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\{ord(ch):03d}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def collect(rows):
    """{speaker: [(broadcast id, text)]} with each broadcast id once per speaker, in the DB's order."""
    lines = {}
    for speaker, broadcast_id, text in rows:
        text = " ".join(text.split())
        seen = lines.setdefault(speaker, {})
        seen.setdefault(broadcast_id, text)
    return {speaker: list(seen.items()) for speaker, seen in lines.items()}


def render(lines, names):
    out = [
        "setfenv(1, VoiceOver)",
        "",
        "-- Generated by pipelines/quests/tools/export_chatter_lines.py; do not edit by hand.",
        "-- What NPCs say out loud in the open world, from the world DB's creature_text: the lines the",
        "-- game gives no sound of its own. id is the broadcast text id, the same one a pack's",
        "-- FollowupLookup names a recording by; the key is the speaker's creature entry.",
        "ChatterLines = {",
    ]
    for speaker in sorted(lines):
        comment = " ".join((names.get(speaker) or "").split())
        out.append(f"    [{speaker}] = {{ -- {comment}")
        for broadcast_id, text in lines[speaker]:
            out.append(f"        {{ id = {broadcast_id}, text = {lua_string(text)} }},")
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    import pymysql

    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--host", default=os.environ.get("COMPENDIUM_MYSQL_HOST", "127.0.0.1"))
    parser.add_argument("--port", type=int, default=int(os.environ.get("COMPENDIUM_MYSQL_PORT", "3317")))
    parser.add_argument("--user", default=os.environ.get("COMPENDIUM_MYSQL_USER", "root"))
    parser.add_argument("--password", default=os.environ.get("COMPENDIUM_MYSQL_PASSWORD", ""))
    parser.add_argument("--database", default=os.environ.get("COMPENDIUM_MYSQL_DATABASE", "world"))
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args()

    db = pymysql.connect(host=args.host, port=args.port, user=args.user, password=args.password,
                         database=args.database, charset="utf8mb4")
    with db.cursor() as cursor:
        cursor.execute(QUERY)
        lines = collect(cursor.fetchall())
        ids = sorted(lines)
        cursor.execute(NAMES.format(", ".join(["%s"] * len(ids))), ids)
        names = dict(cursor.fetchall())
    db.close()

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(lines, names))
    total = sum(len(v) for v in lines.values())
    print(f"wrote {os.path.normpath(args.out)}: {total} lines across {len(lines)} speakers")


if __name__ == "__main__":
    main()
